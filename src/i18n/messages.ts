export const MESSAGES: Record<Language, Record<MessageKey, string>> = { en, ro }

export function translate(key: MessageKey, lang: Language, params?: Record<string, string | number>): string {
  let message = MESSAGES[lang][key] ?? MESSAGES.en[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      message = message.replaceAll(`{${name}}`, String(value))
    }
  }
  return message
}

export function pick(value: Localized, lang: Language): string {
  return value[lang] ?? value.en
}
